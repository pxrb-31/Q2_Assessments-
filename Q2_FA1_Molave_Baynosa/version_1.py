# Modular Calculator Mini-Program

def calculate(a, b, op):
    operations = {
        "1": lambda x, y: x + y,
        "2": lambda x, y: x - y,
        "3": lambda x, y: x * y,
        "4": lambda x, y: "Cannot divide by zero." if y == 0 else x / y,
    }
    func = operations.get(op)
    if func is None:
        return None
    return func(a, b)


def show_menu():
    print("Choose operation:")
    print("1 - Addition")
    print("2 - Subtraction")
    print("3 - Multiplication")
    print("4 - Division")


def main():
    x = int(input("Enter first number: "))
    y = int(input("Enter second number: "))

    show_menu()
    option = input("Enter choice: ")

    answer = calculate(x, y, option)

    if answer is None:
        print("Invalid choice.")
    else:
        print("Result:", answer)

main()

